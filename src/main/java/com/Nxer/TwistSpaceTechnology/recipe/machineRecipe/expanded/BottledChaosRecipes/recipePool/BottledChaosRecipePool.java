/**
 * Balance each chain at the point where players should be able to take its output.
 *
 * <pre>
 * A -> B -> C        Serial          Rutile -> titanium tetrachloride -> titanium.
 * (A or B) -> C      Alternate feeds Ilmenite or bauxite -> rutile.
 * (A + B) -> C       Join            Woven Kevlar + polyurethane resin -> Kevlar plates.
 * A -> (B, C)        Split           Wood -> wood tar, wood vinegar, and wood gas.
 * A -> (B, C) -> D   Split and join  Oil -> light and heavy fuel -> diesel.
 * A -> B -> A        Recycle         Hydrogen peroxide recovery in the prismatic acid line.
 * </pre>
 *
 * Cancel intermediates consumed within the chain and keep surplus coproducts.
 * Count shared upstream batches once. Account for the initial charge of a recycle loop separately.
 *
 * Set credential boundaries at independent feeds, outputs, or unlocks.
 *
 * <pre>
 * Full chain          One platinum metallic powder credential covers the steps to platinum dust.
 * Linked stages       One titanium credential for ore preparation and rutile processing.
 * Stage credentials   Each grade of purified water has its own credential.
 * Separate recipes    One IsaMill credential covers recipes for different ores.
 * </pre>
 *
 * Mark only intended handoffs as key outputs. Other coproducts can be collected.
 * Circuits select a process within the authorized routes. Routes sharing a feed keep the normal match order.
 */
public final class BottledChaosRecipePool {

    public static void registerRecipeChains(BottledChaosRecipeCatalog catalog) {
        BottledChaosTitaniumRecipes.registerRecipeChains(catalog);
        BottledChaosTungstenRecipes.registerRecipeChains(catalog);
        BottledChaosIndiumRecipes.registerRecipeChains(catalog);
        BottledChaosPlatinumRecipes.registerRecipeChains(catalog);
        BottledChaosLanthanideRecipes.registerRecipeChains(catalog);
        BottledChaosNanoExtractionRecipes.registerRecipeChains(catalog);
        BottledChaosNaquadahRecipes.registerRecipeChains(catalog);
        BottledChaosNaquadahFuelRecipes.registerRecipeChains(catalog);
        BottledChaosFusionRecipes.registerRecipeChains(catalog);
        BottledChaosNetheriteRecipes.registerRecipeChains(catalog);
        BottledChaosIsaMillRecipes.registerRecipeChains(catalog);
        BottledChaosPrismaticRecipes.registerRecipeChains(catalog);
        BottledChaosPurifiedWaterRecipes.registerRecipeChains(catalog);
        BottledChaosKevlarRecipes.registerRecipeChains(catalog);
        BottledChaosRadoxRecipes.registerRecipeChains(catalog);
        BottledChaosBiologicalRecipes.registerRecipeChains(catalog);
        BottledChaosPetrochemicalRecipes.registerRecipeChains(catalog);
        BottledChaosWoodChemistryRecipes.registerRecipeChains(catalog);
        if (Config.BottledChaosCycleRecipes) {
            registerCrystalCycles(catalog);
            BottledChaosTesseractRecipes.registerRecipeChains(catalog);
            BottledChaosAdvancedMaterialRecipes.registerRecipeChains(catalog);
        }
        BottledChaosExoticMatterRecipes.registerRecipeChains(catalog);
        BottledChaosIndiumRecipes.registerCombRecipeChains(catalog);
        BottledChaosPlatinumRecipes.registerCombRecipeChains(catalog);
        catalog.registerDeferredReagents(AmmoniaGas);
        catalog.includeSynthesisPath(
            Nitrobenzene,
            LiquidNitrogen,
            SodiumNitrateDust,
            AmmoniumNitrateDust,
            AmmoniumNitrateSolution,
            AmmoniaGas,
            OxalicAcid,
            HexafluorosilicicAcid,
            AceticAcid,
            BoricAcid,
            FormicAcid,
            FermentationBase);
        catalog.includeDecompositionPath(
            MagnesiumChlorideDust,
            AmmoniaGas,
            NitrogenMonoxideGas,
            NitrogenDioxideGas,
            SulfurDioxideGas,
            SulfurTrioxideGas,
            CalciumFluorideFluid);
        // Compilation applies external reagent boundaries after collecting every synthesis path.
        catalog.registerExternalReagents(
            NitricAcid,
            HydrofluoricAcid,
            HydrochloricAcid,
            SulfuricAcid,
            PhosphoricAcid,
            PhthalicAcid,
            NaphthenicAcid,
            DilutedSulfuricAcid,
            DilutedHydrochloricAcid,
            SodiumChlorideDust,
            PotassiumNitrateDust);
    }

    /** Main recipes: close native seed returns, keeping only the highest-yield growth variant per route. */
    private static void registerCrystalCycles(BottledChaosRecipeCatalog catalog) {
        // spotless:off
        // Europium gives 100%, versus mutagen 80% and sludge 60%. One chip returns nine parts.
        catalog.registerChain("crystal_cycle", 1, TierEU.RECIPE_HV, EuropiumMolten,
            new Object[] { RawCrystalChip },
            catalog.markRecipe(ForgeHammer, RawCrystalChip, RawCrystalParts, -1),
            catalog.markRecipe(Autoclave, new Object[] { RawCrystalParts, EuropiumMolten }, RawCrystalChip, -1)).hideInputMarker();

        // Oganesson with a seed: 1 + 2 * 20% exquisite gems. Hammering one exquisite gem returns four seeds.
        catalog.registerChain("cerium_lutetium_garnet", 16, TierEU.RECIPE_UHV, CeriumLutetiumAluminiumOxygenBlendDust,
            new Object[] { ExquisiteCeriumLutetiumAluminiumGarnet },
            catalog.markRecipe(ForgeHammer, ExquisiteCeriumLutetiumAluminiumGarnet, FlawlessCeriumLutetiumAluminiumGarnet, -1),
            catalog.markRecipe(ForgeHammer, FlawlessCeriumLutetiumAluminiumGarnet, CeriumLutetiumAluminiumGarnet, -1),
            catalog.markRecipe(Autoclave,
                new Object[] { CeriumLutetiumAluminiumOxygenBlendDust, CeriumLutetiumAluminiumGarnet, OganessonGas },
                ExquisiteCeriumLutetiumAluminiumGarnet, -1));

        // Keep the vacuum-furnace route independently available; its native recipe is deterministic.
        var vacuum = catalog.registerAlternativeChain("cerium_lutetium_garnet", TierEU.RECIPE_UHV,
            CeriumLutetiumAluminiumOxygenBlendDust, new Object[] { ExquisiteCeriumLutetiumAluminiumGarnet },
            catalog.markRecipe(Macerator, ExquisiteCeriumLutetiumAluminiumGarnet, CeriumLutetiumAluminiumGarnetDust, -1),
            catalog.markRecipe(VacuumFurnace, CeriumLutetiumAluminiumGarnetDust, ExquisiteCeriumLutetiumAluminiumGarnet, -1));
        vacuum.includeSynthesisStep(FluidExtractor, CeriumLutetiumAluminiumOxygenBlendMolten,
            CeriumLutetiumAluminiumOxygenBlendDust, -1);
        // spotless:on
    }
}
